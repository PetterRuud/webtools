export type CategoryFilter = TailwindCategoryId | "all";

export function filterTailwindUtilities(
  utilities: TailwindUtility[],
  options: { query?: string; category?: CategoryFilter } = {},
): TailwindUtility[] {
  const category = options.category ?? "all";
  const normalized = (options.query ?? "").trim().toLowerCase();
  const tokens = normalized ? normalized.split(/\s+/) : [];

  return utilities.filter((item) => {
    if (category !== "all" && item.category !== category) return false;
    if (tokens.length === 0) return true;

    const haystack = [
      item.className,
      item.css,
      item.note ?? "",
      item.category,
      ...(item.keywords ?? []),
    ]
      .join(" ")
      .toLowerCase();

    return tokens.every((token) => haystack.includes(token));
  });
}

export function groupUtilitiesByCategory(
  utilities: TailwindUtility[],
): Array<{ category: TailwindCategory; utilities: TailwindUtility[] }> {
  return TAILWIND_CATEGORIES.filter((c) => c.id !== "all")
    .map((category) => ({
      category,
      utilities: utilities.filter((u) => u.category === category.id),
    }))
    .filter((group) => group.utilities.length > 0);
}
