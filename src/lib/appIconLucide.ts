export function filterLucideIcons(query: string, limit = 96): LucidePick[] {
  const q = query.trim().toLowerCase();
  if (!q) return APP_ICON_LUCIDE.slice(0, limit);
  return APP_ICON_LUCIDE.filter((item) => item.name.toLowerCase().includes(q)).slice(0, limit);
}

/**
 * Sync Lucide → SVG markup (no DOM mount).
 * Keep Lucide’s 0 0 24 24 viewBox — cropping it clips stroke caps.
 * App-icon padding controls visual size instead.
 */
export function lucideToSvgMarkup(Icon: LucideIcon): string {
  const html = renderToStaticMarkup(
    createElement(Icon, {
      size: 24,
      color: "currentColor",
      strokeWidth: 2,
      absoluteStrokeWidth: false,
    }),
  );
  const start = html.indexOf("<svg");
  if (start < 0) throw new Error("Could not render Lucide icon");
  return html.slice(start);
}
